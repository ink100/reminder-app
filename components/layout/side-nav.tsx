export function SideNav() {
  const router = useRouter();
  const pathname = usePathname();

  async function handleLogout() {
    await fetch("/api/auth/logout", { method: "POST" });
    router.push("/auth");
    router.refresh();
  }

  return (
    <aside className="hidden w-56 shrink-0 rounded-2xl border border-slate-200 bg-white p-5 shadow-sm md:flex md:flex-col">
      <div className="mb-6">
        <p className="text-xs uppercase tracking-[0.2em] text-slate-400">Reminder App</p>
        <h1 className="mt-2 text-lg font-semibold text-slate-950">到期提醒</h1>
      </div>
      <nav className="flex-1 space-y-1 text-sm">
        {navItems.map((item) => {
          const isActive = pathname === item.href || (item.href !== "/reminders" && pathname.startsWith(item.href));
          return (
            <Link
              key={item.href}
              className={`group flex items-center gap-2.5 rounded-lg px-3 py-2 font-medium transition-colors ${
                isActive
                  ? "bg-blue-600 text-white shadow-sm"
                  : "text-slate-600 hover:bg-slate-100 hover:text-slate-900"
              }`}
              href={item.href}
            >
              <span
                className={isActive ? "text-white [&>svg]:text-white" : "text-slate-400 group-hover:text-slate-600"}
                style={isActive ? { color: "#ffffff" } : undefined}
              >
                {item.icon}
              </span>
              <span className={isActive ? "text-white" : undefined} style={isActive ? { color: "#ffffff" } : undefined}>
                {item.label}
              </span>
            </Link>
          );
        })}
      </nav>
      <button
        onClick={handleLogout}
        className="mt-4 flex w-full items-center justify-center gap-2 rounded-lg border border-red-200 px-3 py-2 text-sm text-red-600 hover:bg-red-50"
      >
        <svg className="h-4 w-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
        </svg>
        退出登录
      </button>
    </aside>
  );
}
